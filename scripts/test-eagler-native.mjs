import {readFile} from 'node:fs/promises';
import {gunzipSync} from 'node:zlib';
import assert from 'node:assert/strict';
import {createNativeGame} from '../site/runtime/native-game.mjs';
import {GDIFonts} from '../site/runtime/gdi-fonts.mjs';
import {PagedMusic} from '../site/runtime/assets.mjs';
import {musicTracks} from '../site/runtime/music-layout.mjs';
import {prepareNativeMusic} from '../site/runtime/native-music-window.mjs';
const original=process.argv.find(a=>a.startsWith('--original='))?.slice(11);
if(!original)throw new Error('Supply --original=directory');
const load=name=>readFile(new URL('../site/'+name,import.meta.url));
const manifest=JSON.parse(await load('manifest.json'));
const music=new PagedMusic(manifest.music,{silent:true});await music.prepare(musicTracks);
const fonts=await Promise.all(Array.from({length:15},async(_,i)=>JSON.parse(gunzipSync(await load(`fonts/128/${32+2*i}-400.json.gz`)))));
let clock=1;
const game=await createNativeGame(await load('vendor/th10-game.wasm'),{files:new Map([['th10.dat',new Uint8Array(await readFile(original+'/th10.dat'))],['thbgm.dat',music]]),fontBackend:new GDIFonts(gunzipSync(await load('fonts/blend.bin.gz')),fonts),monotonic:()=>clock});
async function step(keys=[],count=1){for(let i=0;i<count;i++){await prepareNativeMusic(music,game.native.store);clock+=1/60;game.step({keys:new Set(keys),milliseconds:17});}}
await step([],150);
for(let i=0;i<12&&game.screen().touch.context!=='gameplay';i++){await step(['KeyZ'],2);await step([],80);}
await step([],100);
assert.equal(game.screen().touch.context,'gameplay');assert.equal(game.screen().touch.ready,true);
game.configureTouch({enabled:true,fire:false,movement:'joystick',joystickFree:false});
game.touchControls({joystickX:10000,joystickY:-20000});
const eightBefore=game.screen().touch;await step();const eightAfter=game.screen().touch;
assert(eightAfter.x>eightBefore.x&&eightAfter.y<eightBefore.y);
assert(Math.abs((eightAfter.x-eightBefore.x)+(eightAfter.y-eightBefore.y))<.03);
game.configureTouch({enabled:true,fire:false,movement:'joystick',joystickFree:true});
game.touchControls({joystickX:10000,joystickY:-20000});
const before=game.screen().touch;await step();const after=game.screen().touch;
assert(after.x>before.x&&after.y<before.y);assert(Math.abs((after.y-before.y)/(after.x-before.x))>1.8);
game.configureTouch({enabled:true,fire:false,movement:'drag',unlimitedTouch:true});game.drag({action:'down'},new Set());game.drag({action:'move',dx:80,dy:-40},new Set());
const unlimitedBefore=game.screen().touch;await step();const unlimitedAfter=game.screen().touch;
assert(unlimitedAfter.x-unlimitedBefore.x>75);assert(unlimitedAfter.y-unlimitedBefore.y<-35);
game.cancelTouch();await step();const cancelled=game.screen().touch;assert.equal(cancelled.x,unlimitedAfter.x);assert.equal(cancelled.y,unlimitedAfter.y);
game.configureTouch({enabled:true,fire:false,movement:'drag',unlimitedTouch:false});game.drag({action:'down'},new Set());game.drag({action:'move',dx:-80,dy:-40},new Set());
const limitedBefore=game.screen().touch;await step();const limitedAfter=game.screen().touch;
assert(Math.hypot(limitedAfter.x-limitedBefore.x,limitedAfter.y-limitedBefore.y)<=limitedBefore.fast+.03);
assert(limitedAfter.x<limitedBefore.x&&limitedAfter.y<limitedBefore.y);
console.log('PASS native eight-way joystick, free joystick, unlimited drag, limited drag and cancel',JSON.stringify({before,after,unlimitedBefore,unlimitedAfter,limitedBefore,limitedAfter}));
game.close();
